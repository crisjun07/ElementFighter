#!/usr/bin/env python3
"""Slice Frostia + Noctis. Pre-processes bg removal on full sheet first (fast)."""
from PIL import Image
import os, sys

DISPLAY = 96

def remove_bg_sheet(img, bg_rgb, tol=38):
    """Remove background from entire sheet at once using putdata — much faster than per-crop."""
    img = img.convert('RGBA')
    r0,g0,b0 = bg_rgb
    t2 = tol * tol
    data = img.getdata()
    new = []
    for (r,g,b,a) in data:
        dr=r-r0; dg=g-g0; db=b-b0
        new.append((0,0,0,0) if dr*dr+dg*dg+db*db < t2 else (r,g,b,a))
    img.putdata(new)
    return img

def save_frame(img, anim, idx, x0,y0,x1,y1, out_dir):
    W,H=img.size
    x0=max(0,min(x0,W)); x1=max(0,min(x1,W))
    y0=max(0,min(y0,H)); y1=max(0,min(y1,H))
    if x1<=x0 or y1<=y0: return
    crop=img.crop((x0,y0,x1,y1))
    crop.thumbnail((DISPLAY,DISPLAY),Image.LANCZOS)
    canvas=Image.new('RGBA',(DISPLAY,DISPLAY),(0,0,0,0))
    canvas.paste(crop,((DISPLAY-crop.width)//2,(DISPLAY-crop.height)//2),crop)
    canvas.save(os.path.join(out_dir,f'{anim}-{idx}.png'),'PNG')

def do_char(sheet_path, char_id, anim_map, bg_rgb, tol=38):
    print(f'Loading {sheet_path}...')
    raw = Image.open(sheet_path).convert('RGBA')
    print(f'Removing background rgb{bg_rgb}...')
    img = remove_bg_sheet(raw, bg_rgb, tol)
    root = f'assets/sprites/{char_id}'
    print(f'Slicing {char_id.upper()}...')
    for anim, coords in anim_map.items():
        out_dir = os.path.join(root, anim)
        os.makedirs(out_dir, exist_ok=True)
        for f in os.listdir(out_dir):
            if f.endswith('.png'): os.remove(os.path.join(out_dir,f))
        for i,(x0,y0,x1,y1) in enumerate(coords):
            save_frame(img, anim, i+1, x0,y0,x1,y1, out_dir)
        print(f'  {anim:<12} {len(coords)} frames')
    print(f'{char_id.upper()} done!\n')

