/** Quick lookup by id */
function getCharacter(id) {
  return CHARACTERS.find(c => c.id === id) || CHARACTERS[0];
}

/** Returns a deep copy with level scaling applied */
function getScaledCharacter(id, level) {
  const base = getCharacter(id);
  const scale = 1 + (level - 1) * 0.07;
  return Object.assign({}, base, {
    maxHP:       Math.round(base.maxHP       * scale),
    attackDmg:   Math.round(base.attackDmg   * scale),
    kickDmg:     Math.round(base.kickDmg     * scale),
    specialDmg:  Math.round(base.specialDmg  * scale),
    ultimateDmg: Math.round(base.ultimateDmg * scale),
    defenseRate: Math.min(0.65, base.defenseRate + (level - 1) * 0.005),
  });
}
